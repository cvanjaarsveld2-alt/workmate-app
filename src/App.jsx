const APP_NAME = "PowerMate";
const STORAGE_KEY = "powermate_app_data_v1";

const blankSettings = {
  companyName: "",
  repName: "",
  defaultReminderTime: "08:00",
  followUpReminderDays: "7",
  pdfFooterNote: "Generated by PowerMate",
};

