function MoreScreen({ go, data, setData }) {
  const [moreView, setMoreView] = useState("main");
  const [salesReport, setSalesReport] = useState({ week: "", visits: "", quotes: "", followUps: "", newLeads: "", summary: "" });

  const saveSalesReport = () => {
    setData((current) => ({
      ...current,
      salesReports: [{ id: makeId("sales"), date: todayISO(), ...salesReport }, ...current.salesReports],
    }));
    setSalesReport({ week: "", visits: "", quotes: "", followUps: "", newLeads: "", summary: "" });
    alert("Sales report saved.");
  };

  const updateSettings = (field, value) => {
    setData((current) => ({ ...current, settings: { ...current.settings, [field]: value } }));
  };

  const exportBackup = () => {
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `powermate-backup-${todayISO()}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const clearAll = () => {
    if (!confirm("This will delete all local PowerMate data on this device. Continue?")) return;
    localStorage.removeItem(STORAGE_KEY);
    setData(starterData);
  };

  if (moreView === "sales") {
    return (
      <div className="space-y-5">
        <Button variant="outline" className="rounded-2xl" onClick={() => setMoreView("main")}>← Back</Button>
        <h1 className="text-2xl font-bold text-slate-900">Sales reports</h1>
        <Card className="rounded-3xl shadow-sm">
          <CardContent className="space-y-4 p-4">
            <Field label="Week / Date" value={salesReport.week} onChange={(v) => setSalesReport((r) => ({ ...r, week: v }))} placeholder="Example: Week 18 / 03 May 2026" />
            <Field label="Total visits" value={salesReport.visits} onChange={(v) => setSalesReport((r) => ({ ...r, visits: v }))} />
            <Field label="Quotes sent" value={salesReport.quotes} onChange={(v) => setSalesReport((r) => ({ ...r, quotes: v }))} />
            <Field label="Follow-ups completed" value={salesReport.followUps} onChange={(v) => setSalesReport((r) => ({ ...r, followUps: v }))} />
            <Field label="New leads" value={salesReport.newLeads} onChange={(v) => setSalesReport((r) => ({ ...r, newLeads: v }))} />
            <Field label="Weekly summary" multiline value={salesReport.summary} onChange={(v) => setSalesReport((r) => ({ ...r, summary: v }))} />
            <Button className="w-full rounded-2xl py-6" onClick={saveSalesReport}>Save sales report</Button>
          </CardContent>
        </Card>
        {data.salesReports.map((r) => (
          <Card key={r.id} className="rounded-3xl shadow-sm">
            <CardContent className="p-4">
              <p className="font-bold">{r.week || r.date}</p>
              <p className="mt-1 text-sm text-slate-600">{r.summary}</p>
            </CardContent>
          </Card>
        ))}
      </div>
    );
  }

  if (moreView === "settings") {
    return (
      <div className="space-y-5">
        <Button variant="outline" className="rounded-2xl" onClick={() => setMoreView("main")}>← Back</Button>
        <h1 className="text-2xl font-bold text-slate-900">Settings</h1>
        <Card className="rounded-3xl shadow-sm">
          <CardContent className="space-y-4 p-4">
            <Field label="Company name" value={data.settings.companyName} onChange={(v) => updateSettings("companyName", v)} placeholder="Example: CC Innovations (PTY) Ltd" />
            <Field label="Technician / Rep name" value={data.settings.repName} onChange={(v) => updateSettings("repName", v)} placeholder="Your name" />
            <Field label="Default reminder time" value={data.settings.defaultReminderTime} onChange={(v) => updateSettings("defaultReminderTime", v)} />
            <Field label="Follow-up reminder days" value={data.settings.followUpReminderDays} onChange={(v) => updateSettings("followUpReminderDays", v)} />
            <Field label="PDF footer note" multiline value={data.settings.pdfFooterNote} onChange={(v) => updateSettings("pdfFooterNote", v)} />
            <Button variant="outline" className="w-full rounded-2xl py-6" onClick={exportBackup}>Export backup</Button>
            <Button variant="danger" className="w-full rounded-2xl py-6" onClick={clearAll}>Clear all local data</Button>
          </CardContent>
        </Card>
      </div>
    );
  }

  return (
    <div className="space-y-5">
      <div>
        <h1 className="text-2xl font-bold text-slate-900">More</h1>
        <p className="text-sm text-slate-500">Reports, reminders and settings.</p>
      </div>
      <div className="space-y-3">
        <BigAction icon={Bell} title="Calendar & Notifications" subtitle="Reminder rules and calendar notes" onClick={() => go("Notifications")} />
        <BigAction icon={Home} title="Install on phone" subtitle="Add PowerMate to iOS or Android home screen" onClick={() => go("Install")} />
        <BigAction icon={BriefcaseBusiness} title="Sales reports" subtitle="Weekly visit report and pipeline" onClick={() => setMoreView("sales")} />
        <BigAction icon={ClipboardList} title="Settings" subtitle="PDF templates, backup and account" onClick={() => setMoreView("settings")} />
      </div>
    </div>
  );
}

